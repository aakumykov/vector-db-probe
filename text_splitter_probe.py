from langchain_text_splitters import RecursiveCharacterTextSplitter

# 2. Исходный текст
text = """
Искусственный интеллект (ИИ) — это область компьютерных наук, посвященная созданию систем, способных выполнять задачи, требующие человеческого интеллекта. 
Эти задачи включают распознавание речи, принятие решений, перевод и визуальное восприятие. 
Машинное обучение является подразделом ИИ, который фокусируется на разработке алгоритмов, позволяющих компьютерам учиться на данных. 
Глубокое обучение, в свою очередь, использует нейронные сети с множеством слоев для анализа различных факторов данных. 
Трансформеры стали прорывом в области обработки естественного языка (NLP). 
Модели, такие как BERT и GPT, основаны на архитектуре трансформеров и показывают выдающиеся результаты. 
SentenceTransformers — это отличная библиотека для создания семантических эмбеддингов предложений и параграфов. 
Она позволяет быстро находить сходство между текстами и используется в задачах поиска и кластеризации. 
При работе с длинными документами важно правильно разбивать их на чанки. 
Если резать текст просто по символам, можно разорвать предложение пополам, что ухудшит качество эмбеддинга. 
Именно поэтому используется разбивка по предложениям с нахлестом (overlap). 
Нахлест помогает сохранить контекст, если важная мысль плавно перетекает из одного абзаца в другой. 
Такой подход значительно повышает точность семантического поиска по базе знаний.
"""

# 3. Настраиваем сплиттер


def split_text_to_chunks(input_text: str, chink_max_size: int = 512, chunk_overlap_percent: int = 30) -> list[str]:

    overlap_len = round(chunk_overlap_percent / 100.0 * chink_max_size)

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=chink_max_size,
        chunk_overlap=overlap_len,
        length_function=len,
        separators=["\n\n", "\n", ". ", " ", ""],
        is_separator_regex=False
    )

    return text_splitter.split_text(input_text)


for i, chunk in enumerate(split_text_to_chunks(text)):
    print(f"--- Чанк {i+1} (длина: {len(chunk)} симв.) ---")
    print(chunk)
    print()
